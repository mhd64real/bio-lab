import { chromium } from 'playwright'
const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } })
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
await page.addInitScript(() => localStorage.setItem('bio-lab:v1', JSON.stringify({ sound: false, phases: { p0: { section: 'observe', data: { mount: { specimen: 'letter-e', bubbles: [] } } } } })))
await page.goto('http://localhost:5180/#/p0')
await page.waitForTimeout(1500)
const S = () => page.evaluate(() => window.__scope)
const before = await S()
await page.keyboard.press('3'); await page.keyboard.down('PageUp'); await page.waitForTimeout(600); await page.keyboard.up('PageUp')
await page.keyboard.down('ArrowLeft'); await page.waitForTimeout(300); await page.keyboard.up('ArrowLeft')
const after = await S()
console.log('step 1 locked: objective', before.objective, '->', after.objective, '| z', before.stageZ, '->', after.stageZ)
console.log('toast:', await page.locator('.lock-toast').innerText().catch(() => 'none'))
console.log('disabled buttons:', await page.locator('.station-controls button:disabled').count(), 'enabled:', await page.locator('.station-controls button:enabled').count())
await page.screenshot({ path: 'shots/locked.png' })
await page.keyboard.press('l'); await page.waitForTimeout(100)
console.log('lamp allowed:', (await S()).lampOn)
console.log(errors)
await browser.close()
